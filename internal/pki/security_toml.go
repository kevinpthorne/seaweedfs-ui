package pki

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"seaweedfs-ui/internal/config"
)

// EnsureSecurityToml creates the .seaweedfs/security.toml file required by weed shell gRPC.
// It writes to /tmp/seaweedfs/.seaweedfs/security.toml (under HOME=/tmp/seaweedfs)
// or the configured SecurityTomlPath.
// If TLS is disabled (cfg.Enabled == false), it returns "", nil.
func EnsureSecurityToml(cfg config.TLSConfig) (string, error) {
	if !cfg.Enabled {
		return "", nil
	}

	// Determine destination path and base directory
	var targetPath string
	var homeDir string

	if cfg.SecurityTomlPath != "" {
		targetPath = cfg.SecurityTomlPath
		homeDir = filepath.Dir(targetPath)
	} else {
		homeDir = os.Getenv("HOME")
		if homeDir == "" {
			homeDir = "/tmp/seaweedfs"
		}
		targetPath = filepath.Join(homeDir, ".seaweedfs", "security.toml")
	}

	targetDir := filepath.Dir(targetPath)
	if err := os.MkdirAll(targetDir, 0700); err != nil {
		return "", fmt.Errorf("create directory %q: %w", targetDir, err)
	}

	var b strings.Builder
	b.WriteString("# Auto-generated by seaweedfs-ui. DO NOT EDIT.\n\n")

	// 1. [grpc] section - Root CA for gRPC server verification
	if cfg.CAFile != "" {
		b.WriteString("[grpc]\n")
		b.WriteString(fmt.Sprintf("ca = %q\n\n", cfg.CAFile))
	}

	// 2. [grpc.client] section - Client certificate and key for weed shell mTLS
	if cfg.CertFile != "" && cfg.KeyFile != "" {
		b.WriteString("[grpc.client]\n")
		b.WriteString(fmt.Sprintf("cert = %q\n", cfg.CertFile))
		b.WriteString(fmt.Sprintf("key  = %q\n\n", cfg.KeyFile))
	}

	// 3. [https.client] section - Client certificate and CA for outgoing HTTPS
	if cfg.CAFile != "" || (cfg.CertFile != "" && cfg.KeyFile != "") {
		b.WriteString("[https.client]\n")
		b.WriteString("enabled = true\n")
		if cfg.CertFile != "" && cfg.KeyFile != "" {
			b.WriteString(fmt.Sprintf("cert = %q\n", cfg.CertFile))
			b.WriteString(fmt.Sprintf("key  = %q\n", cfg.KeyFile))
		}
		if cfg.CAFile != "" {
			b.WriteString(fmt.Sprintf("ca   = %q\n", cfg.CAFile))
		}
		b.WriteString("\n")
	}

	content := []byte(b.String())

	// Write target file with strict 0600 permissions
	tmpFile := targetPath + ".tmp"
	if err := os.WriteFile(tmpFile, content, 0600); err != nil {
		if errDirect := os.WriteFile(targetPath, content, 0600); errDirect != nil {
			return "", fmt.Errorf("write security.toml %q: %w", targetPath, errDirect)
		}
	} else {
		if err := os.Rename(tmpFile, targetPath); err != nil {
			_ = os.Remove(tmpFile)
			if errDirect := os.WriteFile(targetPath, content, 0600); errDirect != nil {
				return "", fmt.Errorf("write security.toml %q: %w", targetPath, errDirect)
			}
		}
	}

	// Also write secondary path ($HOME/security.toml) for direct weed shell lookup
	if homeDir != "" && strings.HasSuffix(targetPath, filepath.Join(".seaweedfs", "security.toml")) {
		secondaryPath := filepath.Join(homeDir, "security.toml")
		_ = os.WriteFile(secondaryPath, content, 0600)
	}

	return targetPath, nil
}
